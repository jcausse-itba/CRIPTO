#!/usr/bin/env python3
"""
Steganography Comparative Analyzer (LSB1 vs LSB4 vs LSBI)

Computes fidelity metrics (modified bytes/bits, per-channel breakdown, max delta,
MSE, PSNR) between original 24-bpp BMP V3 carrier images and stego outputs
generated by `stegobmp`, and produces visual comparison assets for the report.
"""

from __future__ import annotations

import argparse
import math
import struct
from dataclasses import dataclass
from pathlib import Path
from typing import Sequence

from PIL import Image, ImageDraw, ImageFont


FONT_REGULAR_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
FONT_BOLD_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"


@dataclass
class BmpInfo:
    path: Path
    width: int
    height: int
    data_offset: int
    total_carrier_bytes: int
    raw_pixels: bytes


@dataclass
class StegoMetrics:
    carrier_name: str
    algorithm: str
    width: int
    height: int
    total_carrier_bytes: int
    max_capacity_bytes: int
    payload_bytes: int
    modified_bytes: int
    modified_bits: int
    ch_modified: tuple[int, int, int]  # (B, G, R)
    max_abs_delta: int
    mse: float
    psnr: float


def load_font(bold: bool = False, size: int = 16) -> ImageFont.FreeTypeFont | ImageFont.ImageFont:
    path = FONT_BOLD_PATH if bold else FONT_REGULAR_PATH
    try:
        return ImageFont.truetype(path, size=size)
    except OSError:
        return ImageFont.load_default()


def read_bmp(path: Path) -> BmpInfo:
    data = path.read_bytes()
    if len(data) < 54 or data[:2] != b"BM":
        raise ValueError(f"{path} is not a valid BMP file")

    data_offset = struct.unpack_from("<I", data, 10)[0]
    bi_size, width, height, planes, bpp, compression = struct.unpack_from("<IiiHHI", data, 14)
    if bi_size != 40 or bpp != 24 or compression != 0 or planes != 1:
        raise ValueError(f"{path} must be an uncompressed 24-bpp BMP V3 image")

    abs_h = abs(height)
    row_bytes = width * 3
    stride = ((row_bytes + 3) // 4) * 4
    total_bytes = stride * abs_h
    return BmpInfo(
        path=path,
        width=width,
        height=abs_h,
        data_offset=data_offset,
        total_carrier_bytes=total_bytes,
        raw_pixels=data[data_offset : data_offset + total_bytes],
    )


def max_capacity(algorithm: str, carrier_bytes: int) -> int:
    if algorithm == "LSB1":
        return carrier_bytes // 8
    if algorithm == "LSB4":
        return carrier_bytes // 2
    if algorithm == "LSBI":
        if carrier_bytes < 4:
            return 0
        rem = carrier_bytes - 4
        skipped_red = (rem + 1) // 3
        return (rem - skipped_red) // 8
    raise ValueError(f"Unknown algorithm: {algorithm}")


def analyze_pair(carrier: BmpInfo, stego_path: Path, algorithm: str, payload_bytes: int, label: str) -> StegoMetrics:
    stego = read_bmp(stego_path)
    if len(carrier.raw_pixels) != len(stego.raw_pixels):
        raise ValueError(f"Size mismatch between {carrier.path} and {stego_path}")

    n = len(carrier.raw_pixels)
    diff_bytes = 0
    diff_bits = 0
    sq_err = 0
    max_delta = 0
    ch_diff = [0, 0, 0]  # B, G, R order in BMP pixel stream

    for idx, (a, b) in enumerate(zip(carrier.raw_pixels, stego.raw_pixels)):
        if a != b:
            diff_bytes += 1
            diff_bits += (a ^ b).bit_count()
            d = abs(a - b)
            sq_err += d * d
            ch_diff[idx % 3] += 1
            if d > max_delta:
                max_delta = d

    mse = sq_err / n
    psnr = 10.0 * math.log10((255.0 * 255.0) / mse) if mse > 0 else float("inf")

    return StegoMetrics(
        carrier_name=label,
        algorithm=algorithm,
        width=carrier.width,
        height=carrier.height,
        total_carrier_bytes=n,
        max_capacity_bytes=max_capacity(algorithm, n),
        payload_bytes=payload_bytes,
        modified_bytes=diff_bytes,
        modified_bits=diff_bits,
        ch_modified=(ch_diff[0], ch_diff[1], ch_diff[2]),
        max_abs_delta=max_delta,
        mse=mse,
        psnr=psnr,
    )


def save_compressed_thumbnails(carriers: Sequence[tuple[str, Path]], out_dir: Path) -> None:
    """Create lightweight JPEG previews inside out_dir to keep the exported PDF compact."""
    for stem, src_path in carriers:
        with Image.open(src_path) as img:
            rgb = img.convert("RGB")
            rgb.thumbnail((520, 520), Image.Resampling.LANCZOS)
            out_path = out_dir / f"{stem}_thumb.jpg"
            rgb.save(out_path, format="JPEG", quality=88, optimize=True)


def generate_diff_map(
    orig_path: Path,
    stego_paths: dict[str, Path],
    out_path: Path,
    title: str,
) -> None:
    """
    Generate a 1x3 spatial alteration heatmap highlighting modified pixels over a
    dimmed version of the original image.
    """
    algs = ["LSB4", "LSB1", "LSBI"]
    panel_w = 340
    margin = 20
    header_h = 56
    label_h = 46

    with Image.open(orig_path) as orig_im:
        orig_rgb = orig_im.convert("RGB")
    w, h = orig_rgb.size
    panel_h = int(round(panel_w * (h / w)))

    canvas_w = margin * 4 + panel_w * 3
    canvas_h = header_h + panel_h + label_h + margin
    canvas = Image.new("RGB", (canvas_w, canvas_h), (250, 251, 253))
    draw = ImageDraw.Draw(canvas)

    font_title = load_font(bold=True, size=20)
    font_sub = load_font(bold=True, size=15)
    font_small = load_font(bold=False, size=13)

    draw.text((margin, 16), title, fill=(20, 32, 54), font=font_title)

    orig_px = orig_rgb.load()
    for col, alg in enumerate(algs):
        with Image.open(stego_paths[alg]) as stego_im:
            stego_rgb = stego_im.convert("RGB")
        stego_px = stego_rgb.load()

        vis = Image.new("RGB", (w, h))
        vis_px = vis.load()
        changed_rows = 0
        for y in range(h):
            row_changed = False
            for x in range(w):
                r0, g0, b0 = orig_px[x, y]
                r1, g1, b1 = stego_px[x, y]
                if r0 != r1 or g0 != g1 or b0 != b1:
                    row_changed = True
                    # Highlight altered channels vividly over dark background
                    dr = 255 if r0 != r1 else 25
                    dg = 230 if g0 != g1 else 25
                    db = 255 if b0 != b1 else 25
                    vis_px[x, y] = (dr, dg, db)
                else:
                    # Dimmed original context (28% luminance)
                    vis_px[x, y] = (int(r0 * 0.28), int(g0 * 0.28), int(b0 * 0.28))
            if row_changed:
                changed_rows += 1

        vis_scaled = vis.resize((panel_w, panel_h), Image.Resampling.BOX)
        px_x = margin + col * (panel_w + margin)
        px_y = header_h
        canvas.paste(vis_scaled, (px_x, px_y))
        draw.rectangle([px_x - 1, px_y - 1, px_x + panel_w, px_y + panel_h], outline=(180, 190, 205), width=1)

        pct_rows = 100.0 * changed_rows / h
        draw.text((px_x, px_y + panel_h + 6), f"{alg}", fill=(11, 83, 148), font=font_sub)
        draw.text(
            (px_x, px_y + panel_h + 25),
            f"Alcance: {changed_rows}/{h} filas ({pct_rows:.1f}%)",
            fill=(70, 80, 95),
            font=font_small,
        )

    canvas.save(out_path, format="PNG", optimize=True)


def generate_bitplane_comparison(
    orig_path: Path,
    stego_paths: dict[str, Path],
    out_path: Path,
) -> None:
    """
    Show a zoomed bottom strip (where BMP embedding starts) comparing:
    - Top row: 4-LSB plane ((val & 0x0F) * 17) across Original, LSB4, LSB1, LSBI
    - Bottom row: 1-LSB Red-channel plane ((R & 1) * 255) showing LSB1 noise vs LSBI preservation
    """
    with Image.open(orig_path) as orig_im:
        orig_rgb = orig_im.convert("RGB")
    w, h = orig_rgb.size

    # Crop bottom 90 rows at 1:1 pixel resolution so transition lines of LSB4 (~13 rows),
    # LSB1 (~49 rows) and LSBI (~73 rows) are razor-sharp without resampling artifacts.
    crop_w = min(270, w)
    crop_h = min(90, h)
    x0 = (w - crop_w) // 2
    y0 = h - crop_h

    cols = ["Original", "LSB4", "LSB1", "LSBI"]
    sources = {"Original": orig_rgb}
    for alg in ["LSB4", "LSB1", "LSBI"]:
        with Image.open(stego_paths[alg]) as im:
            sources[alg] = im.convert("RGB")

    scale_w = crop_w
    scale_h = crop_h
    margin_x = 18
    left_label_w = 150
    top_h = 72
    row_gap = 28

    canvas_w = left_label_w + len(cols) * scale_w + (len(cols) + 1) * margin_x
    canvas_h = top_h + scale_h * 2 + row_gap + 38
    canvas = Image.new("RGB", (canvas_w, canvas_h), (250, 251, 253))
    draw = ImageDraw.Draw(canvas)

    font_title = load_font(bold=True, size=19)
    font_col = load_font(bold=True, size=15)
    font_row = load_font(bold=True, size=14)
    font_small = load_font(bold=False, size=12)

    draw.text(
        (20, 14),
        f"Comparación de Planos de Bits (Franja inferior {crop_w}×{crop_h} px)",
        fill=(20, 32, 54),
        font=font_title,
    )

    row_specs = [
        ("Plano 4-LSB\n(RGB & 0x0F × 17)", "lsb4"),
        ("Plano 1-LSB\n(Solo Canal Rojo)", "red_lsb1"),
    ]

    for r_idx, (r_label, mode) in enumerate(row_specs):
        ry = top_h + r_idx * (scale_h + row_gap)
        draw.multiline_text((20, ry + 34), r_label, fill=(35, 48, 70), font=font_row, spacing=4)

        for c_idx, name in enumerate(cols):
            cx = left_label_w + margin_x + c_idx * (scale_w + margin_x)
            if r_idx == 0:
                draw.text((cx, 46), name, fill=(11, 83, 148), font=font_col)

            src = sources[name].crop((x0, y0, x0 + crop_w, y0 + crop_h))
            s_px = src.load()
            out_tile = Image.new("RGB", (crop_w, crop_h))
            o_px = out_tile.load()

            for yy in range(crop_h):
                for xx in range(crop_w):
                    r, g, b = s_px[xx, yy]
                    if mode == "lsb4":
                        o_px[xx, yy] = ((r & 0x0F) * 17, (g & 0x0F) * 17, (b & 0x0F) * 17)
                    else:
                        v = 255 if (r & 0x01) else 0
                        o_px[xx, yy] = (v, v, v)

            canvas.paste(out_tile, (cx, ry))
            draw.rectangle([cx - 1, ry - 1, cx + scale_w, ry + scale_h], outline=(160, 172, 190), width=1)

    draw.text(
        (left_label_w + margin_x, canvas_h - 28),
        "Nota: En BMP el almacenamiento es bottom-up; LSB4 introduce un bloque de ruido neto abajo, mientras LSBI deja el plano 1-LSB Rojo intacto.",
        fill=(80, 90, 105),
        font=font_small,
    )
    canvas.save(out_path, format="PNG", optimize=True)


def generate_metrics_chart(metrics: Sequence[StegoMetrics], out_path: Path) -> None:
    """Draw a two-panel chart: (Left) PSNR in dB, (Right) Modified bytes by channel (B, G, R)."""
    w, h = 1160, 470
    canvas = Image.new("RGB", (w, h), (255, 255, 255))
    draw = ImageDraw.Draw(canvas)

    font_title = load_font(bold=True, size=18)
    font_sub = load_font(bold=True, size=15)
    font_lbl = load_font(bold=False, size=13)
    font_val = load_font(bold=True, size=12)

    algs = ["LSB1", "LSB4", "LSBI"]
    lookup = {(m.carrier_name, m.algorithm): m for m in metrics}

    # --- Left Panel: PSNR (dB) ---
    draw.text((40, 20), "Fidelidad Visual: PSNR (dB) — Mayor es Mejor", fill=(20, 32, 54), font=font_title)
    lx0, ly0, lx1, ly1 = 75, 75, 530, 375
    draw.line([(lx0, ly0), (lx0, ly1), (lx1, ly1)], fill=(90, 100, 115), width=2)

    y_min, y_max = 40.0, 70.0
    for tick in [40, 45, 50, 55, 60, 65, 70]:
        ty = ly1 - int((tick - y_min) / (y_max - y_min) * (ly1 - ly0))
        draw.line([(lx0 - 5, ty), (lx1, ty)], fill=(230, 234, 240) if tick > 40 else (90, 100, 115), width=1)
        draw.text((lx0 - 38, ty - 8), f"{tick}", fill=(80, 90, 105), font=font_lbl)

    carriers = [("cat_v3.bmp", (26, 115, 232)), ("eiffel_tower_v3.bmp", (14, 159, 110))]
    group_w = (lx1 - lx0) // len(algs)
    bar_w = 46

    for idx, alg in enumerate(algs):
        gx = lx0 + idx * group_w + group_w // 2
        draw.text((gx - 18, ly1 + 12), alg, fill=(20, 32, 54), font=font_sub)

        for c_idx, (cname, color) in enumerate(carriers):
            m = lookup[(cname, alg)]
            bx0 = gx - bar_w - 4 if c_idx == 0 else gx + 4
            bx1 = bx0 + bar_w
            clamped = max(y_min, min(y_max, m.psnr))
            by0 = ly1 - int((clamped - y_min) / (y_max - y_min) * (ly1 - ly0))
            draw.rectangle([bx0, by0, bx1, ly1 - 1], fill=color)
            draw.text((bx0 + 2, by0 - 17), f"{m.psnr:.2f}", fill=color, font=font_val)

    # Legend left panel
    draw.rectangle([100, 418, 116, 434], fill=carriers[0][1])
    draw.text((124, 418), "cat_v3.bmp", fill=(40, 50, 65), font=font_lbl)
    draw.rectangle([260, 418, 276, 434], fill=carriers[1][1])
    draw.text((284, 418), "eiffel_tower_v3.bmp", fill=(40, 50, 65), font=font_lbl)

    # --- Right Panel: Modified Bytes per Channel (cat_v3.bmp) ---
    draw.text((610, 20), "Bytes Modificados por Canal en cat_v3.bmp (B, G, R)", fill=(20, 32, 54), font=font_title)
    rx0, ry0, rx1, ry1 = 655, 75, 1115, 375
    draw.line([(rx0, ry0), (rx0, ry1), (rx1, ry1)], fill=(90, 100, 115), width=2)

    max_ch = 30000
    for tick in [0, 5000, 10000, 15000, 20000, 25000, 30000]:
        ty = ry1 - int(tick / max_ch * (ry1 - ry0))
        draw.line([(rx0 - 5, ty), (rx1, ty)], fill=(230, 234, 240) if tick > 0 else (90, 100, 115), width=1)
        draw.text((rx0 - 50, ty - 8), f"{tick // 1000}k" if tick > 0 else "0", fill=(80, 90, 105), font=font_lbl)

    ch_colors = [
        ("Canal Azul (B)", (37, 99, 235)),
        ("Canal Verde (G)", (22, 163, 74)),
        ("Canal Rojo (R)", (220, 38, 38)),
    ]
    r_group_w = (rx1 - rx0) // len(algs)
    r_bar_w = 34
    r_gap = 10

    for idx, alg in enumerate(algs):
        gx = rx0 + idx * r_group_w + r_group_w // 2
        draw.text((gx - 18, ry1 + 12), alg, fill=(20, 32, 54), font=font_sub)
        m = lookup[("cat_v3.bmp", alg)]

        for ch_i, (_, color) in enumerate(ch_colors):
            val = m.ch_modified[ch_i]
            total_grp_w = 3 * r_bar_w + 2 * r_gap
            bx0 = gx - total_grp_w // 2 + ch_i * (r_bar_w + r_gap)
            bx1 = bx0 + r_bar_w
            bh = int(val / max_ch * (ry1 - ry0))
            by0 = ry1 - bh
            if bh > 0:
                draw.rectangle([bx0, by0, bx1, ry1 - 1], fill=color)
            lbl = f"{val / 1000:.1f}k" if val >= 1000 else str(val)
            draw.text((bx0 + (12 if val == 0 else -1), by0 - 17), lbl, fill=color, font=font_val)

    # Legend right panel
    lx_cursor = 670
    for label, color in ch_colors:
        draw.rectangle([lx_cursor, 418, lx_cursor + 16, 434], fill=color)
        draw.text((lx_cursor + 22, 418), label, fill=(40, 50, 65), font=font_lbl)
        lx_cursor += 155

    canvas.save(out_path, format="PNG", optimize=True)


def print_metrics_table(metrics: Sequence[StegoMetrics]) -> None:
    header = (
        f"{'Portadora':<20} | {'Alg':<4} | {'Cap. Máx':>9} | {'Bytes Mod.':>16} | "
        f"{'Bits Mod.':>9} | {'Canales (B / G / R)':>22} | {'Δ Máx':>5} | {'MSE':>8} | {'PSNR (dB)':>9}"
    )
    print(header)
    print("-" * len(header))
    for m in metrics:
        pct = 100.0 * m.modified_bytes / m.total_carrier_bytes
        ch_str = f"{m.ch_modified[0]:,}/{m.ch_modified[1]:,}/{m.ch_modified[2]:,}"
        print(
            f"{m.carrier_name:<20} | {m.algorithm:<4} | {m.max_capacity_bytes:>8,}B | "
            f"{m.modified_bytes:>8,} ({pct:4.2f}%) | {m.modified_bits:>9,} | "
            f"{ch_str:>22} | {m.max_abs_delta:>5d} | {m.mse:>8.4f} | {m.psnr:>9.2f}"
        )


def main() -> None:
    parser = argparse.ArgumentParser(description="Analyze LSB1, LSB4 and LSBI stego BMP outputs.")
    parser.add_argument("--images-dir", type=Path, default=Path("images"), help="Directory containing BMP images")
    parser.add_argument("--out-dir", type=Path, default=Path("doc/informe"), help="Output directory for PNG/JPG assets")
    parser.add_argument("--payload", type=Path, default=Path("README.md"), help="Embedded payload file")
    args = parser.parse_args()

    payload_file_size = args.payload.stat().st_size
    ext_with_null = len(args.payload.suffix) + 1  # e.g. ".md\0" -> 4 bytes
    total_embedded_bytes = 4 + payload_file_size + ext_with_null

    specs = [
        ("cat", "cat_v3.bmp"),
        ("eiffel_tower", "eiffel_tower_v3.bmp"),
    ]
    algs = ["LSB1", "LSB4", "LSBI"]

    all_metrics: list[StegoMetrics] = []
    for stem, orig_name in specs:
        carrier = read_bmp(args.images_dir / orig_name)
        for alg in algs:
            stego_path = args.images_dir / f"{stem}_README_{alg}.bmp"
            all_metrics.append(analyze_pair(carrier, stego_path, alg, total_embedded_bytes, orig_name))

    print(f"Embedded file: {args.payload} ({payload_file_size:,} B -> {total_embedded_bytes:,} B total wire payload)\n")
    print_metrics_table(all_metrics)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    save_compressed_thumbnails(
        [(stem, args.images_dir / orig_name) for stem, orig_name in specs],
        args.out_dir,
    )

    cat_orig = args.images_dir / "cat_v3.bmp"
    cat_stegos = {alg: args.images_dir / f"cat_README_{alg}.bmp" for alg in algs}
    generate_diff_map(
        cat_orig,
        cat_stegos,
        args.out_dir / "comparacion_mapa_cambios.png",
        "Mapa Espacial de Píxeles Alterados en cat_v3.bmp (README.md embebido)",
    )
    generate_bitplane_comparison(
        cat_orig,
        cat_stegos,
        args.out_dir / "comparacion_planos_bits.png",
    )
    generate_metrics_chart(
        all_metrics,
        args.out_dir / "comparacion_metricas.png",
    )
    print(f"\nGenerated visual assets in {args.out_dir}/")


if __name__ == "__main__":
    main()
